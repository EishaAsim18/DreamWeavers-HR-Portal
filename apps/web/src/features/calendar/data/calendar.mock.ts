/**
 * Anyone who self-registers (see `mockRegister` in `auth.mock.ts`) is written
 * straight into the same localStorage-backed employee directory the
 * Employees page reads from. Reading it here — rather than duplicating a
 * third "people" list — means every existing `getPerson`/calendar/teams/
 * Meet Dreams call site picks up newly registered people for free.
 */
function loadRegisteredPeople(): CalendarPerson[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.employees)
    if (!raw) return []
    const employees = JSON.parse(raw) as Employee[]
    return employees
      .filter((e) => !CALENDAR_PEOPLE.some((p) => p.id === e.id))
      .map((e): CalendarPerson => ({
        id: e.id,
        name: `${e.firstName} ${e.lastName}`,
        initials: `${e.firstName[0] ?? ''}${e.lastName[0] ?? ''}`.toUpperCase(),
        role: e.role,
        department: e.department,
        jobTitle: e.jobTitle,
        avatarColor: e.avatarColor,
      }))
  } catch {
    return []
  }
}

/** Full roster — seeded org chart plus anyone who has self-registered. */
export const getAllPeople = (): CalendarPerson[] => [...CALENDAR_PEOPLE, ...loadRegisteredPeople()]

export const getPerson = (id: string): CalendarPerson | undefined =>
  CALENDAR_PEOPLE.find((p) => p.id === id) ?? loadRegisteredPeople().find((p) => p.id === id)

